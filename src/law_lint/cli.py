from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

from law_lint.context import derive_context, describe_context, find_answers_file, load_answers
from law_lint.engine import Linter
from law_lint.models import Finding


def format_findings(findings: list[Finding], *, verbose: bool = False) -> str:
    """Format findings for terminal output."""
    if not findings:
        return "✨ No legal or compliance triggers matched."

    # Group by rule id
    by_rule: dict[str, list[Finding]] = {}
    for f in findings:
        by_rule.setdefault(f.rule.id, []).append(f)

    lines: list[str] = [
        f"⚠️  law-lint: Detected {len(findings)} trigger match(es) across {len(by_rule)} compliance area(s):\n"
    ]

    for rule_id, rule_findings in by_rule.items():
        rule = rule_findings[0].rule
        badge = f"[{rule.enforcement}]" if rule.enforcement else ""
        lines.append(f"📌 {badge} {rule.title} ({rule_id})")
        lines.append(f"   💡 要約: {rule.summary}")
        lines.append("   🔎 検出箇所:")
        for rf in rule_findings[:5]:
            lines.append(f"      - {rf.file_path}:{rf.line_number} (hit: '{rf.matched_text}')")
            if verbose:
                lines.append(f"        line: {rf.context_line}")
        if len(rule_findings) > 5:
            lines.append(f"      ... and {len(rule_findings) - 5} more occurrence(s)")
        lines.append("")

    return "\n".join(lines).strip()


def prepare(args: argparse.Namespace) -> int:
    """Derive the applicable compliance set from .copier-answers.yml."""
    answers_path = Path(args.answers) if args.answers else find_answers_file(args.repo)
    if answers_path is None:
        print(
            "⚠️  No .copier-answers.yml found under "
            f"{args.repo!r} — this project was not generated by a copier template "
            "(or the answers file is elsewhere; pass --answers PATH).",
            file=sys.stderr,
        )
        return 2

    context = derive_context(load_answers(answers_path))
    base = Linter.from_yaml(args.rules) if args.rules else Linter()
    scoped = base.for_context(context)
    skipped = [r for r in base.rules if r not in scoped.rules]

    print(f"📋 law-lint prepare — {answers_path}")
    for line in describe_context(context):
        print(f"   {line}")
    print()
    print(f"✅ Applicable rules ({len(scoped.rules)} of {len(base.rules)}):")
    for r in scoped.rules:
        print(f"   [{r.enforcement}] {r.id}: {r.title}")
        print(f"        💡 {r.summary}")
    if skipped:
        print()
        print(f"⏭️  Gated out for this project ({len(skipped)}): " + ", ".join(r.id for r in skipped))

    if args.write:
        payload = {"rules": [r.to_dict() for r in scoped.rules]}
        out = answers_path.parent / ".law-lint-rules.yml"
        out.write_text(yaml.safe_dump(payload, allow_unicode=True, sort_keys=False), encoding="utf-8")
        print(f"\n📝 Wrote {out}")
        print("   Commit it: check/diff loads .law-lint-rules.yml automatically when --rules is not given.")
    else:
        print("\nℹ️  Pass --write to materialize .law-lint-rules.yml next to the answers file.")
    return 0


def resolve_linter(args: argparse.Namespace) -> Linter:
    """Select the active rule set: --rules > prepared file > copier-answers scope > all builtins."""
    repo = Path(getattr(args, "repo", "."))
    if args.rules:
        return Linter.from_yaml(args.rules)
    prepared = repo / ".law-lint-rules.yml"
    answers = find_answers_file(repo)
    if prepared.is_file():
        return Linter.from_yaml(prepared)
    if answers is not None and not getattr(args, "all", False):
        scoped = Linter.for_project(answers)
        print(
            f"ℹ️  Scoped to {len(scoped.rules)} rules via {answers} (pass --all to scan everything)",
            file=sys.stderr,
        )
        return scoped
    return Linter()


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="law-lint",
        description="Fast linter matching source files and git diffs against legal and ethical triggers.",
    )
    parser.add_argument("--rules", type=Path, default=None, help="Custom rules YAML file")
    parser.add_argument("-v", "--verbose", action="store_true", help="Show full matched lines")
    parser.add_argument("--strict", action="store_true", help="Exit with code 1 if any L2 rule triggers")

    sub = parser.add_subparsers(dest="subcommand", required=True)

    # prepare
    p_prep = sub.add_parser(
        "prepare",
        help="Read .copier-answers.yml, infer the project type, and show the applicable compliance rules",
    )
    p_prep.add_argument("--repo", default=".", help="Project root containing .copier-answers.yml")
    p_prep.add_argument("--answers", default=None, help="Explicit path to a copier answers file")
    p_prep.add_argument("--write", action="store_true", help="Write .law-lint-rules.yml next to the answers file")

    # diff
    p_diff = sub.add_parser("diff", help="Scan git diff for modified lines")
    p_diff.add_argument("--staged", action="store_true", help="Scan staged changes instead of unstaged")
    p_diff.add_argument("--repo", default=".", help="Target repository directory (default: current)")
    p_diff.add_argument(
        "--all", action="store_true", help="Scan with every rule, ignoring the copier-derived project scope"
    )

    # check
    p_check = sub.add_parser("check", help="Scan specific files or directories")
    p_check.add_argument("paths", nargs="+", help="Files or directories to scan")
    p_check.add_argument("--repo", default=".", help="Project root for copier-derived scoping")
    p_check.add_argument(
        "--all", action="store_true", help="Scan with every rule, ignoring the copier-derived project scope"
    )

    # list-rules
    p_list = sub.add_parser("list-rules", help="List all active detection rules")
    p_list.add_argument("--repo", default=".", help="Project root for copier-derived scoping")
    p_list.add_argument("--all", action="store_true", help="List every rule, ignoring the copier-derived project scope")

    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)

    if args.subcommand == "prepare":
        return prepare(args)

    linter = resolve_linter(args)

    if args.subcommand == "list-rules":
        print(f"Active compliance rules ({len(linter.rules)}):")
        for r in linter.rules:
            print(f"- [{r.enforcement}] {r.id}: {r.title}")
            print(f"  Summary: {r.summary}")
        return 0

    if args.subcommand == "diff":
        findings = linter.scan_git_diff(staged=args.staged, repo_dir=args.repo)
    elif args.subcommand == "check":
        findings = linter.scan_paths(args.paths)
    else:
        findings = []

    print(format_findings(findings, verbose=args.verbose))

    if args.strict and any(f.rule.enforcement == "L2" for f in findings):
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
