@cache
def _ja_resource() -> dict[str, Any]:
    text = (files("daimonion") / "locales" / "ja.yml").read_text(encoding="utf-8")
    data = yaml.safe_load(text) or {}
    return data if isinstance(data, dict) else {}


def _locale_lang(environ: Mapping[str, str]) -> str | None:
    for var in ("LC_ALL", "LC_MESSAGES", "LANG"):
        value = environ.get(var, "")
        if value:
            return "ja" if value.lower().startswith("ja") else None
    return None


def resolve_lang(explicit: str | None = None, environ: Mapping[str, str] | None = None) -> str:
    """``explicit`` > ``DAIMONION_LANG`` > POSIX locale > English."""
    env = os.environ if environ is None else environ
    for candidate in (explicit, env.get("DAIMONION_LANG"), _locale_lang(env)):
        if candidate:
            lang = candidate.split("_")[0].split(".")[0].lower()
            if lang in LANGS:
                return lang
    return DEFAULT_LANG


def resolve_emoji(disabled: bool = False, environ: Mapping[str, str] | None = None) -> bool:
    """Icons are on unless ``--no-emoji`` or ``DAIMONION_NO_EMOJI`` (non-empty, not ``0``) says otherwise."""
    env = os.environ if environ is None else environ
    return not disabled and env.get("DAIMONION_NO_EMOJI", "") in ("", "0")


@dataclass(frozen=True)
class UI:
    """The language and icon style one CLI invocation prints in."""

    lang: str = DEFAULT_LANG
    emoji: bool = True
    _messages: Mapping[str, str] = field(default_factory=dict, repr=False, compare=False)
    _rules: Mapping[str, Mapping[str, str]] = field(default_factory=dict, repr=False, compare=False)

    @classmethod
    def create(cls, lang: str = DEFAULT_LANG, *, emoji: bool = True) -> UI:
        if lang == "ja":
            resource = _ja_resource()
            return cls(lang, emoji, resource.get("messages") or {}, resource.get("rules") or {})
        return cls(lang, emoji)

    def icon(self, role: str) -> str:
        return ICONS[role] if self.emoji else ""

    def t(self, key: str, **values: object) -> str:
        """The message ``key`` in this language, formatted with ``values``."""
        return self._messages.get(key, MESSAGES[key]).format(**values)

    def line(self, role: str, key: str, **values: object) -> str:
        """``t(key)`` prefixed with the ``role`` icon."""
        return self.icon(role) + self.t(key, **values)

    def _rule_text(self, rule: Rule, attr: str) -> str:
        canonical = getattr(rule, attr)
        builtin = _BUILTIN_TEXT.get(rule.id)
        # Translate only a builtin rule whose English text is unchanged, so a
        # custom rule that reuses a builtin id keeps its own wording.
        if builtin is None or builtin.get(attr) != canonical:
            return canonical
        return self._rules.get(rule.id, {}).get(attr) or canonical

    def rule_title(self, rule: Rule) -> str:
        return self._rule_text(rule, "title")

    def rule_summary(self, rule: Rule) -> str:
        return self._rule_text(rule, "summary")


_BUILTIN_TEXT: dict[str, dict[str, str]] = {
    rule.id: {"title": rule.title, "summary": rule.summary} for rule in BUILTIN_RULES
}

DEFAULT_UI = UI.create()
